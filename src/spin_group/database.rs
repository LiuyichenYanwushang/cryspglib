//! Oriented spin-space group database: collinear subset.
//!
//! The pinned source is the public FindSpinGroup database
//! (<https://database.findspingroup.com>) filtered by
//! `configuration=Collinear`.  The generated table stores the
//! **quotient signature** of every record: one spatial operation
//! `{W|t}` plus the net channel action on the collinear order parameter.
//! Continuous spin rotations about the collinear axis and the universal
//! spin-only stabilizer are not repeated as separate rows; they are the
//! canonical kernel of the collinear quotient.
//!
//! The table is generated by `scripts/generate_ssg_collinear_data.py` from the
//! release pinned in [`collinear_ssg_release_source_sha256`] and the manifest
//! SHA in [`collinear_ssg_manifest_sha256`].  See [`collinear_ssg_record_count`]
//! for the record count.
//!
//! This module is independent of the magnetic-space-group database: a
//! spin-space group is not a magnetic group and the spin channel is never
//! encoded in a `time_reversal` bit.

use super::SpinGroupKind;
use super::collinear::CollinearAction;

mod ssg_collinear_data;

/// Chen-Liu four-index identifier plus the trailing letter, e.g.
/// `221.200.1.1.L`.
///
/// The four indices are `G0.L0.it.ik`; the trailing ASCII letter is the
/// database's family letter (`L` in the current release).  Construction and
/// parsing validate the supported ranges; display reproduces the canonical
/// identifier exactly.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct SpinSpaceGroupNumber {
    g0: u16,
    l0: u16,
    it: u16,
    ik: u16,
    letter: u8,
}

impl SpinSpaceGroupNumber {
    /// Construct from parts, validating the database ranges.
    pub fn new(g0: u16, l0: u16, it: u16, ik: u16, letter: char) -> Option<Self> {
        if !(1..=230).contains(&g0)
            || !(1..=230).contains(&l0)
            || !(1..=48).contains(&it)
            || !(1..=8).contains(&ik)
            || !letter.is_ascii_alphabetic()
        {
            return None;
        }
        Some(Self {
            g0,
            l0,
            it,
            ik,
            letter: letter as u8,
        })
    }

    /// Parse a canonical identifier such as `221.200.1.1.L`.
    pub fn parse(text: &str) -> Option<Self> {
        let mut parts = text.split('.');
        let g0 = parts.next()?.parse::<u16>().ok()?;
        let l0 = parts.next()?.parse::<u16>().ok()?;
        let it = parts.next()?.parse::<u16>().ok()?;
        let ik = parts.next()?.parse::<u16>().ok()?;
        let letter = parts.next()?;
        if parts.next().is_some() {
            return None;
        }
        let mut letters = letter.chars();
        let letter = letters.next()?;
        if letters.next().is_some() {
            return None;
        }
        Self::new(g0, l0, it, ik, letter)
    }

    /// First index `G0` (parent space-group number in the database frame).
    pub const fn g0(self) -> u16 {
        self.g0
    }
    /// Second index `L0`.
    pub const fn l0(self) -> u16 {
        self.l0
    }
    /// Third index `it`.
    pub const fn it(self) -> u16 {
        self.it
    }
    /// Fourth index `ik`.
    pub const fn ik(self) -> u16 {
        self.ik
    }
    /// Trailing family letter.
    pub const fn letter(self) -> char {
        self.letter as char
    }

    pub(crate) const fn from_parts_unchecked(
        g0: u16,
        l0: u16,
        it: u16,
        ik: u16,
        letter: u8,
    ) -> Self {
        Self {
            g0,
            l0,
            it,
            ik,
            letter,
        }
    }
}

impl core::fmt::Display for SpinSpaceGroupNumber {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(
            formatter,
            "{}.{}.{}.{}.{}",
            self.g0, self.l0, self.it, self.ik, self.letter as char
        )
    }
}

/// One row of the collinear quotient signature: a spatial operation and the
/// net channel action on the collinear order parameter.
///
/// `translation` is a fractional translation in the database's `G0` frame,
/// normalized to `[0, 1)`; it is stored as `f64` because the source exports
/// use small rational translations and the identification layer compares them
/// with the same tolerance as the group certificate.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SpinSpaceGroupOperation {
    /// Spatial rotation `W` in `GL(3,Z)`.
    pub rotation: [[i32; 3]; 3],
    /// Fractional translation `t` in `[0, 1)^3`.
    pub translation: [f64; 3],
    /// Net channel action: `Preserve` (`+1`) or `Swap` (`-1`).
    pub channel: CollinearAction,
}

/// One pinned collinear spin-space-group record.
#[derive(Debug, Clone)]
pub struct SpinSpaceGroupRecord {
    /// Canonical Chen-Liu identifier.
    pub number: SpinSpaceGroupNumber,
    /// Canonical identifier string (same as `number.to_string()`).
    pub identifier: &'static str,
    /// Plain-text International notation derived from the database export.
    pub international_symbol: &'static str,
    /// Original LaTeX International notation as exported by the database.
    pub international_notation_latex: &'static str,
    /// Magnetic-order category of the record (always `Collinear` here).
    pub configuration: SpinGroupKind,
    /// Database group type (`typeI`, `typeII`, ...).
    pub group_type: &'static str,
    /// Spin-space point-group symbol as exported (`∞m`, `∞/mm`, ...).
    pub spin_point_group: &'static str,
    /// Export fields `tspin`, `gs`, `gso` retained verbatim.
    pub tspin: i8,
    /// Export field `gs`.
    pub gs: i8,
    /// Export field `gso`.
    pub gso: &'static str,
    /// Database basis label (`G0` or `L0`) of the operation frame.
    pub basis: &'static str,
    /// Number of operations in the source record (including continuous
    /// generators that are not expanded into the quotient signature).
    pub num_all_elements: u32,
    /// Quotient signature: spatial operations with their channel action.
    pub operations: &'static [SpinSpaceGroupOperation],
}

/// All pinned collinear records in canonical identifier order.
pub fn collinear_spin_space_groups() -> impl ExactSizeIterator<Item = &'static SpinSpaceGroupRecord>
{
    ssg_collinear_data::RECORDS.iter()
}

/// Look up one record by its typed number.
pub fn collinear_spin_space_group(
    number: SpinSpaceGroupNumber,
) -> Option<&'static SpinSpaceGroupRecord> {
    ssg_collinear_data::RECORDS
        .binary_search_by(|record| record.number.cmp(&number))
        .ok()
        .map(|index| &ssg_collinear_data::RECORDS[index])
}

/// Look up one record by its canonical identifier string.
pub fn collinear_spin_space_group_by_identifier(
    identifier: &str,
) -> Option<&'static SpinSpaceGroupRecord> {
    ssg_collinear_data::RECORDS
        .iter()
        .find(|record| record.identifier == identifier)
}


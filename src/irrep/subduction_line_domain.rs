//! Exact parameter-domain census for the frozen parametric-k line sources.
//!
//! A frozen source lives on the line `k(t) = t . v`.  Its **frozen** little
//! character table is the little group of the *direction*, i.e. the group of the
//! generic point: the operations `R` with `R^-T v = v` modulo the parent
//! reciprocal lattice.  At isolated rational parameters additional operations
//! fix `k(t)` as well, the little group is strictly larger there, and the frozen
//! table describes an induced value rather than the actual line irrep (the
//! engine labels those parameters `ParameterKind::Formal`, see
//! [`super::decompose::LineSubduction::parameter_kind`]).
//!
//! This module answers **where** those parameters are, exactly, instead of
//! sampling denominators: for one operation `R` the condition is
//! `R^-T k(t) - k(t) = t . w_R  in  L*_parent` with `w_R = R^-T v - v`, and the
//! solution set of `t . w  in  L*` is a subgroup of `Q`, so it is generated by
//! one exact rational step.  The exceptional parameters in `[0, 1)` are the
//! residues of that step, a finite set per operation.
//!
//! Everything here is exact `i128` rational arithmetic on the twelfth grid the
//! rest of the subduction layer uses; no floating point and no grid search whose
//! cost grows with a denominator.  The derivation of the step:
//!
//! 1. `t . w in Z^3` holds exactly for `t in c Z`, where `c` is the least
//!    common multiple of the rationals `q_i / p_i` taken over the nonzero
//!    components `w_i = p_i / q_i` in lowest terms (a component with `w_i = 0`
//!    constrains nothing).
//! 2. Writing `t = c j` and `u = c w in Z^3`, the centring conditions of `L*`
//!    are congruences on `j`: the set of valid `j` is `n Z` with `n | e`, where
//!    `e` is the exponent of `L*` over `Z^3` (`e = 1` for P, `2` for A/B/C/I/F,
//!    `3` for R).  `n` is found by scanning `j = 1 ..= 6`, so the scan bound is a
//!    property of the centring type, not of the cocycle.
//! 3. The step is `c n` and the exceptional parameters are its residues
//!    `j (c n) mod 1` for `j = 0 .. denominator(c n) - 1`.
//!
//! The step comes with two independent controls.  Internally, every hit of the
//! finite scan must be a multiple of the smallest one, otherwise the solution
//! set would not be a subgroup and the module reports
//! [`SubductionError::DomainCensusInconsistent`] instead of a wrong domain.
//! Externally, [`minimal_parameter_step_via_coordinates`] recomputes the same
//! step through the lattice's own coordinate map, an algorithm that shares no
//! arithmetic with the centring scan; the corpus gate compares the two on every
//! `(source, rotation)` pair.
//!
//! Scope: directions that are **reciprocal lattice vectors** of the group they
//! belong to.  Only then is `k(t + 1) = k(t) + v` the same point of the zone, the
//! little group periodic in `t` with period one, and the residue representation
//! of the domain valid.  The frozen corpus satisfies this for all 73 sources and
//! for all 1,006 folded child directions; anything else is rejected with
//! [`SubductionError::ParameterDomainOutOfScope`] instead of being reported in a
//! representation that silently merges distinct parameters.  The child-side
//! census below is the same computation after folding `v` through the embedding,
//! so it covers the folded little co-group of every isotropy record of a source.
//!
//! # The projective class on a domain
//!
//! Decomposing a line source at a parameter `t` needs the **projective**
//! characters of the child little co-group of the folded point `q(t) = t . q1`:
//! its factor system is
//!
//! ```text
//! omega_t(R, S) = chi_{q(t)}(lambda_RS),  lambda_RS = tau_R + R tau_S - tau_RS,
//! ```
//!
//! with one chosen child operation `(R, tau_R)` per rotation and `lambda_RS` the
//! **unreduced** defect, an element of the child lattice `L` (see
//! `subduction_catalogue`).  Whether the class of `omega_t` in `H^2(P, U(1))` can
//! change inside a domain decides whether one representative parameter per domain
//! is enough, so it is the question this section settles.
//!
//! Let `P = { R : R^{-T} q1 = q1 }`, the **exact** stabiliser of the direction,
//! i.e. the rotations with `w_R = R^{-T} q1 - q1 = 0`.  On a domain of the census
//! the little co-group of `q(t)` is exactly `P`: a rotation with `w_R != 0`
//! satisfies `t . w_R in L*` only at the isolated parameters the census lists, so
//! it enters the little co-group, if at all, at an exceptional parameter and never
//! inside a domain.  For `R in P` the defect identity
//! `lambda_RS + lambda_{R S,T} = R lambda_{S,T} + lambda_{R,ST}` together with
//! `(R^T - I) q1 = 0` gives
//!
//! ```text
//! omega_s(R,S) omega_s(RS,T) = omega_s(S,T) omega_s(R,ST)   for every real s,
//! ```
//!
//! so `s -> omega_s` is a family of factor systems on `P`, and `s -> [omega_s]` is
//! a homomorphism from the divisible group `(R, +)` into the finite group
//! `H^2(P, U(1))`; a homomorphism from a divisible group to a finite group is
//! trivial.  Hence:
//!
//! **Local theorem (fixed direction).**  With `beta_t(R) = exp(2 pi i t (q1 .
//! tau_R))` the factor system of the fixed direction is an explicit coboundary,
//!
//! ```text
//! omega_t(R,S) = beta_t(R) beta_t(S) / beta_t(R S)     for every real t,
//! ```
//!
//! because `R^T q1 = q1` for every `R in P` makes the unreduced defect
//! `lambda_RS = tau_R + R tau_S - tau_RS` and the symmetrised form agree after
//! pairing with `q1`.  Equivalently, `s -> [omega_s]` is a homomorphism from the
//! divisible group `(R,+)` into the finite group `H^2(P, U(1))`, hence trivial.
//! In particular the class is trivial at *every* parameter, not only at the probed
//! ones, and a non-coboundary family is reachable only at an exceptional parameter
//! of the little co-group, where the stabiliser is strictly larger and this
//! argument does not apply.
//!
//! **Withdrawn add-on (full decomposition).**  Earlier revisions concluded from
//! the theorem that "the only parameter dependence left in the decomposition is
//! the gauge, so the multiplicities are constant on each domain and one
//! representative parameter per domain suffices".  That is **withdrawn**
//! (external review, 2026-09-26, accepted): the partition it referred to is
//! generated from the **reference** folded direction only
//! ([`child_exceptional_parameters`]), while the reported decomposition depends
//! on the whole star — every folded arm's own little co-group and every pairwise
//! arm identification.  Corpus witnesses, both now permanent regressions: ordinal
//! 10030 (SG 196 `DT1` to #18) has reference candidates `{0, 1/4, 1/2, 3/4}` yet
//! another folded arm acquires an order-four little co-group with a
//! **non-trivial** cocycle at `t = 1/8`; ordinal 10038 (SG 196 `DT1` to P1) keeps
//! every child little group trivial yet its arms merge at `t = 1/8` (six
//! one-dimensional blocks of multiplicity one at `1/9` and `1/7`, four blocks of
//! multiplicities 2, 1, 1, 2 at `1/8`).
//!
//! # The full-star partition
//!
//! [`full_star_partition`] replaces the reference-only reading: the predicates
//! `t (R_H^{-T} v_i - v_i) in L*_H` for every folded arm and
//! `t (R_H^{-T} v_i - v_j) in L*_H` for every ordered arm pair and every child
//! rotation, all solved with the same exact step solver, with a zero difference
//! recorded as a relation that holds on the whole domain instead of as a
//! boundary.  Every parameter of `[0, 1)` is then either a boundary or inside one
//! open interval on which the folded geometry — which arms share a point, which
//! points share a child star, and every point's little co-group — is constant,
//! because each of those quantities is a truth value of one of the enumerated
//! predicates.  On such an interval no rotation enters a little co-group, so every
//! arm's rotations fix its direction *exactly* and the local theorem above makes
//! that arm's factor system a coboundary at every parameter of the interval: the
//! projective content cannot change between boundaries either.
//!
//! Measured on the corpus (the permanent regression
//! `the_full_star_partition_of_the_frozen_corpus_is_the_eighth_grid`): the
//! partition of all 5,756 `(record, label)` pairs is exactly the eighth grid
//! `{0, 1/8, 1/4, 3/8, 1/2, 5/8, 3/4, 7/8}`, 2,273 of those pairs are strictly
//! larger than the reference-only candidate set, and every one of the 50,226
//! folded arms is a child reciprocal lattice vector (the periodicity premise, now
//! checked per **arm** and not only for the reference direction).
//!
//! What the partition does **not** carry is the engine-side control: that the
//! reported multiplicities and target sources are constant on an interval, and
//! that the `stored`/`constructed` provenance — which may change *inside* an
//! interval, because a stored child `k` is hit at isolated parameters — does not
//! change the decomposition.  That comparison is R6.7 cards 5-6 (`AGENTS.md`);
//! until it runs, decomposition constancy rests on the derivation above and is
//! not measured by this module.
//!
//! The theorem's own premise is the **child** side: the census gate counts, for
//! every record and label, the rotations with `w_R = 0` and compares the count
//! with the child order at the generic sample.  The parent-side check (all 341
//! operations of the 73 frozen little groups fix their direction exactly, with
//! `parent_domain`'s `generic_order` counting the same set) is a separate control
//! — it pins the frozen parent table as the exact stabiliser — not the premise.
//!
//! An earlier formulation of the child-side check used membership `w_R in L*`
//! instead of exact fixity.  On this corpus that is **vacuous**, not merely
//! weaker: the scope fence requires the direction to be a reciprocal lattice
//! vector and every rotation preserves that lattice, so *every* rotation
//! satisfies it (2,580/2,580 parent, 28,713/28,713 child).  It also does not imply
//! that `chi_{s q1} . lambda` is a factor system for every real `s` — on that
//! rotation set the cocycle identity fails at 4,877 of 51,804 (pair, `s`) probes,
//! while on the exact stabiliser it holds 51,804/51,804.  The figure "24,430
//! violations" quoted here before is not reproducible as described (the described
//! count gives 5,117 pairs) and is withdrawn.


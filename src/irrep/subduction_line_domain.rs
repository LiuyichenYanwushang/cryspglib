/// Scan bound for the congruence on `j`; it only has to cover the possible
/// exponents of a reciprocal lattice over `Z^3` (1 for P, 2 for A/B/C/I/F,
/// 3 for R), so it is a constant of the centring classification.
const CENTRING_SCAN: i128 = 6;

/// The identity rotation, as the Hall data stores it.
const IDENTITY_ROTATION: Mat3I = [[1, 0, 0], [0, 1, 0], [0, 0, 1]];

/// One parameter at which the little group of `k(t)` is strictly larger than the
/// frozen one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExceptionalParameter {
    /// The exact parameter in `[0, 1)`.
    pub parameter: Rat,
    /// Order of the little co-group at this parameter (number of distinct parent
    /// rotations that fix `k(t)` modulo the parent reciprocal lattice).
    pub order: usize,
    /// `order - generic_order`: how many operations join the frozen little
    /// group here.
    pub added: usize,
}

/// The parameter domain of one frozen line source, before any child is chosen.
#[derive(Debug, Clone)]
pub struct ParentDomain {
    /// Parent space group number.
    pub parent_sg: u8,
    /// Frozen source label, e.g. `DT1`.
    pub label: &'static str,
    /// Frozen direction in the parent's conventional reciprocal basis.
    pub direction: Vec3R,
    /// Order of the little co-group of the direction: the generic stabiliser.
    pub generic_order: usize,
    /// Number of distinct rotations in the parent's point group.
    pub parent_rotations: usize,
    /// Exceptional parameters in `[0, 1)`, ascending.  `t = 0` is always one of
    /// them (every rotation fixes `k = 0`).
    pub exceptional: Vec<ExceptionalParameter>,
}

impl ParentDomain {
    /// Whether `t` is an exceptional parameter of this source.
    ///
    /// The parameter is reduced modulo one first: `k(t + 1) = k(t) + v` with
    /// `v` a parent reciprocal lattice vector, so the little group is periodic in
    /// `t` with period one.
    pub fn is_exceptional(&self, parameter: &Rat) -> bool {
        let reduced = reduce_modulo_one(*parameter);
        self.exceptional
            .iter()
            .any(|entry| entry.parameter == reduced)
    }
}

/// The representative of a rational in `[0, 1)`.
fn reduce_modulo_one(value: Rat) -> Rat {
    let denominator = value.denominator();
    let numerator = value.numerator().rem_euclid(denominator);
    Rat::new(numerator, denominator).unwrap_or(Rat::ZERO)
}

/// The reciprocal lattice of one space group, in the conventional reciprocal
/// frame the frozen `direction` fields live in.
///
/// Fails only for an out-of-range number.  The lattice is the one of the **stored
/// Hall setting** of that space group number ([`exact_primitive_basis`] switches
/// on the centring of `SG_DATA_HALL[sg]`), which is what the frozen directions
/// and the census use; 27 space group numbers have Hall settings with a different
/// centring, so "the reciprocal lattice of SG `n`" is shorthand for that setting.
/// The census uses it on the parent of a line source and on the child a source
/// folds into.
pub fn reciprocal_lattice(sg: u8) -> Result<Lattice, SubductionError> {
    Lattice::new(exact_primitive_basis(sg)?)?.reciprocal()
}

/// Refuse a direction that is not a lattice vector of `lattice`.
///
/// The census represents a domain by the residues of an exact step in `[0, 1)`,
/// which is only the same set of little groups when `k(t + 1) = k(t) + v` with
/// `v` in the reciprocal lattice; see the module documentation.  The frozen
/// corpus passes this for all 73 sources and all 1,006 folded child directions
/// (the census gate re-checks the parent side on every source), so the guard is a
/// scope fence for future sources rather than a live code path.
pub fn require_reciprocal_direction(
    lattice: &Lattice,
    direction: &Vec3R,
    sg: u8,
    label: &'static str,
) -> Result<(), SubductionError> {
    if lattice.contains(direction)? {
        return Ok(());
    }
    Err(SubductionError::ParameterDomainOutOfScope { sg, label })
}

/// Exact scaling of a rational vector.
fn scale(vector: &Vec3R, factor: &Rat) -> Result<Vec3R, SubductionError> {
    let mut values = [Rat::ZERO; 3];
    for (axis, value) in values.iter_mut().enumerate() {
        *value = factor.checked_mul(vector.get(axis))?;
    }
    Ok(Vec3R::new(values))
}

/// `|value|` as a checked operation: `i128::MIN` has no positive counterpart, so
/// the census reports `RationalOverflow` instead of panicking in a debug build.
fn absolute(value: i128) -> Result<i128, SubductionError> {
    value
        .checked_abs()
        .ok_or(SubductionError::RationalOverflow {
            operation: "parameter-domain absolute value",
        })
}

fn gcd(left: i128, right: i128) -> Result<i128, SubductionError> {
    let (mut a, mut b) = (absolute(left)?, absolute(right)?);
    while b != 0 {
        let next = a % b;
        a = b;
        b = next;
    }
    Ok(a)
}

fn lcm(left: i128, right: i128) -> Result<i128, SubductionError> {
    if left == 0 || right == 0 {
        return Ok(0);
    }
    let divisor = gcd(left, right)?;
    let scaled = (left / divisor)
        .checked_mul(right)
        .ok_or(SubductionError::RationalOverflow {
            operation: "parameter-domain lcm",
        })?;
    absolute(scaled)
}

/// Whether the factor system of one folded direction is a **coboundary** at one
/// parameter, decided without the catalogue's order bound.
///
/// This is the exact per-point decision the domain theorem does not cover: at an
/// exceptional parameter the little co-group of `q(t)` is strictly larger than the
/// generic one, the divisibility argument of the module documentation does not
/// apply, and the class may be non-trivial.  The catalogue's one-dimensional
/// solver answers the same question only for `|P_q| <= MAX_ORDER` (where an empty
/// solution set means "non-coboundary"), which leaves the 1,980 census probes with
/// child orders 12 to 48 undecided; this entry point decides them too.
///
/// The class is a function of the child, the folded direction and the parameter
/// only: the cocycle is built from the child's own operations and `q(t)`, so the
/// parent star does not enter it.
pub fn child_cocycle_is_a_coboundary(
    child_sg: u8,
    folded: &Vec3R,
    parameter: Rat,
) -> Result<bool, StarError> {
    let child_reciprocal = reciprocal_lattice(child_sg)?;
    if !folded.is_zero() {
        require_reciprocal_direction(&child_reciprocal, folded, child_sg, "folded direction")?;
    }
    let q = scale(folded, &parameter)?;
    let co_group = super::catalogue::little_co_group(child_sg, &q, &child_reciprocal)?;
    co_group.cocycle_is_a_coboundary()
}

/// Whether two parameters of the same folded direction carry the **same**
/// projective class, i.e. whether `omega_first / omega_second` is a coboundary.
///
/// This is the complete invariant the construction offers: two factor systems
/// represent the same class in `H^2(P, U(1))` exactly when their quotient is a
/// coboundary, and the decision above is exact for every order.  The domain
/// theorem says the answer is `true` for any two parameters of one domain (both
/// classes are trivial); the census measures it directly at the exceptional
/// parameters, where the little co-group is larger.
pub fn child_cocycles_are_cohomologous(
    child_sg: u8,
    folded: &Vec3R,
    first: Rat,
    second: Rat,
) -> Result<bool, StarError> {
    let child_reciprocal = reciprocal_lattice(child_sg)?;
    if !folded.is_zero() {
        require_reciprocal_direction(&child_reciprocal, folded, child_sg, "folded direction")?;
    }
    let first_group =
        super::catalogue::little_co_group(child_sg, &scale(folded, &first)?, &child_reciprocal)?;
    let second_group =
        super::catalogue::little_co_group(child_sg, &scale(folded, &second)?, &child_reciprocal)?;
    first_group.cohomologous_to(&second_group)
}

/// The rational step generating `{ t : t . w in lattice }`, or `None` when `w`
/// is zero (the operation fixes every point of the line).
///
/// The returned step `s > 0` generates the solution subgroup.  For `w` **in**
/// `lattice` the parameters in `[0, 1)` are exactly the residues `j s mod 1`,
/// `j = 0 .. denominator - 1`; for `w` outside the lattice the solution set is
/// not periodic in `t`, so those residues are *not* the parameters and the
/// public entry points refuse such a direction (see
/// [`require_reciprocal_direction`]).
///
/// **Precondition:** for `w` different from zero, `lattice` must be contained in
/// `Z^3` in the frame of `w`, and the quotient `Z^3 / lattice` must have exponent
/// at most [`CENTRING_SCAN`].  Both hold for the reciprocal lattice of the stored
/// Hall setting of every space group number (index at most four, exponent at most
/// three; asserted by
/// `every_space_group_reciprocal_lattice_is_integral_with_small_exponent`).  The
/// centring scan integrates first and applies the congruences afterwards, which
/// is only complete under those hypotheses; a lattice with fractional rows would
/// need `Lattice::coordinates` instead.  The first hypothesis is checked for
/// `w != 0` and reported as [`SubductionError::DomainCensusInconsistent`], so a
/// future caller cannot get a silently wrong step.  `w = 0` needs neither: zero is
/// in every lattice, so the answer is `Ok(None)` for any lattice, before the
/// check.  The second hypothesis is sufficient rather than necessary -- the scan
/// errors exactly when the least admissible centring multiple exceeds the bound,
/// which an exponent above [`CENTRING_SCAN`] implies but does not exhaust (a
/// lattice like `diag(4, 3, 1)` still answers many `w` correctly).
pub fn minimal_parameter_step(
    lattice: &Lattice,
    w: &Vec3R,
) -> Result<Option<Rat>, SubductionError> {
    if w.is_zero() {
        return Ok(None);
    }
    // The scan integrates first (`t . w in Z^3`), so it needs a lattice inside
    // the integer lattice; see the precondition in the documentation.
    if !lattice.rows().is_integral() {
        return Err(SubductionError::DomainCensusInconsistent {
            reason: "the centring scan requires a lattice contained in Z^3",
        });
    }
    // 1. `t . w in Z^3` <=> `t in c Z`, with `c` the lcm of `q_i / p_i` over the
    //    nonzero components `w_i = p_i / q_i` in lowest terms.
    let mut accumulated: Option<Rat> = None;
    for axis in 0..3 {
        let value = w.get(axis);
        if value.is_zero() {
            continue;
        }
        // The generator is taken positive: the solution set is symmetric
        // (`t` and `-t` either both work or both fail), so only its positive
        // generator matters.
        let component = Rat::new(absolute(value.denominator())?, absolute(value.numerator())?)?;
        accumulated = Some(match accumulated {
            None => component,
            Some(current) => Rat::new(
                lcm(current.numerator(), component.numerator())?,
                gcd(current.denominator(), component.denominator())?,
            )?,
        });
    }
    let Some(c) = accumulated else {
        return Ok(None);
    };
    // 2. Centring congruences on `j` for `t = c j`.
    let u = scale(w, &c)?;
    if !u.is_integral() {
        return Err(SubductionError::DomainCensusInconsistent {
            reason: "the integrality step did not clear the denominators",
        });
    }
    let mut hits: Vec<i128> = Vec::new();
    for j in 1..=CENTRING_SCAN {
        let factor = Rat::new(j, 1)?;
        if lattice.contains(&scale(&u, &factor)?)? {
            hits.push(j);
        }
    }
    let Some(&n) = hits.first() else {
        return Err(SubductionError::DomainCensusInconsistent {
            reason: "no centring multiple of the integrality step lands in the lattice",
        });
    };
    // The solution set is a subgroup of `Z` here, so every hit of the scan must
    // be a multiple of the smallest one.  A violation disproves the arithmetic
    // behind the scan and is reported rather than smoothed over.
    if hits.iter().any(|hit| *hit % n != 0) {
        return Err(SubductionError::DomainCensusInconsistent {
            reason: "a scanned multiple lands in the lattice without the minimum dividing it",
        });
    }

    let step = c.checked_mul(Rat::new(n, 1)?)?;
    if step.denominator() <= 0 || step.numerator() <= 0 {
        return Err(SubductionError::DomainCensusInconsistent {
            reason: "the parameter step is not positive",
        });
    }
    Ok(Some(step))
}

/// Sort exact rationals by value without floating point.
///
/// `Rat` deliberately does not implement `Ord`, so the parameters are compared
/// through a common denominator: the denominators here are the grid sizes of the
/// census, and an overflow is reported instead of falling back to `f64`.
fn sort_parameters(mut values: Vec<Rat>) -> Result<Vec<Rat>, SubductionError> {
    let mut common: i128 = 1;
    for value in &values {
        common = lcm(common, value.denominator())?;
    }
    let mut keyed: Vec<(i128, Rat)> = Vec::with_capacity(values.len());
    for value in values.drain(..) {
        let scaled = value
            .numerator()
            .checked_mul(common / value.denominator())
            .ok_or(SubductionError::RationalOverflow {
                operation: "parameter-domain ordering",
            })?;
        keyed.push((scaled, value));
    }
    keyed.sort_by_key(|(key, _)| *key);
    Ok(keyed.into_iter().map(|(_, value)| value).collect())
}

/// The residues of a step in `[0, 1)`.
fn residues_of(step: Rat) -> Result<Vec<Rat>, SubductionError> {
    let denominator = step.denominator();
    let mut out = Vec::with_capacity(usize::try_from(denominator).unwrap_or(0));
    for j in 0..denominator {
        let factor = Rat::new(j, 1)?;
        out.push(reduce_modulo_one(step.checked_mul(factor)?));
    }
    Ok(out)
}

/// Result of the brute-force cross-check of one exact enumeration.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GridCheck {
    /// Number of `(rotation, grid parameter)` predicates recomputed.
    pub checks: usize,
    /// Predicates where the direct group computation disagreed with the
    /// enumeration.  A non-zero value disproves the census's arithmetic.
    pub mismatches: usize,
}

/// Recompute `R fixes k(t)` directly from the group on a uniform grid and
/// compare it with the exact enumeration.
///
/// What this check does and does not establish: the *predicate* is recomputed
/// from the group (`Lattice::preserves`, i.e. `contains(R^-T k - k)`) instead of
/// from the residue list, so it validates the geometry of the condition and the
/// residue enumeration.  It shares the step algebra (`minimal_parameter_step`)
/// with the enumeration, so it cannot detect a wrong step; and a grid whose
/// denominator is not a multiple of a step misses that step's parameters
/// entirely, which is why the corpus gate uses denominators that cover the
/// measured grid and why [`minimal_parameter_step_via_coordinates`] exists as a
/// second, arithmetic-independent step.  A coarse grid can only weaken the check;
/// while the enumeration is correct it can never produce a mismatch.
pub fn verify_against_grid(
    lattice: &Lattice,
    direction: &Vec3R,
    rotations: &[Mat3I],
    denominator: i128,
) -> Result<GridCheck, SubductionError> {
    let mut check = GridCheck {
        checks: 0,
        mismatches: 0,
    };
    for rotation in rotations {
        let image = Mat3R::from_ints(*rotation)
            .inverse()?
            .transpose()
            .checked_mul_vector(direction)?;
        let w = image.checked_sub(direction)?;
        let residues = match minimal_parameter_step(lattice, &w)? {
            Some(step) => residues_of(step)?,
            // `w = 0`: the operation fixes every parameter.
            None => Vec::new(),
        };
        for k in 0..denominator {
            let parameter = Rat::new(k, denominator)?;
            let actual = lattice.preserves(*rotation, &scale(direction, &parameter)?)?;
            let predicted = if w.is_zero() {
                true
            } else {
                residues.contains(&parameter)
            };
            check.checks += 1;
            if actual != predicted {
                check.mismatches += 1;
            }
        }
    }
    Ok(check)
}

/// The distinct rotations of one space group's data-Hall operations.
pub fn rotation_set(sg: u8) -> Result<Vec<Mat3I>, SubductionError> {
    let hall = strict_sg_hall_ops(sg)?;
    let mut rotations: Vec<Mat3I> = Vec::new();
    for operation in &hall.operations {
        if !rotations.contains(&operation.rotation()) {
            rotations.push(operation.rotation());
        }
    }
    Ok(rotations)
}

/// The candidate parameters in `[0, 1)` induced by one direction: the union over
/// the given rotations of the residues of their steps, each with the number of
/// rotations fixing `k(t)`.
///
/// **Internal.**  The residue representation is only valid when `direction` is a
/// lattice vector of `lattice`; this function cannot check that (it has no space
/// group for the error text), so the public entry points [`parent_domain`] and
/// [`child_exceptional_parameters`] call [`require_reciprocal_direction`] first
/// and are the only supported way to obtain a domain.
fn exceptional_parameters(
    lattice: &Lattice,
    direction: &Vec3R,
    rotations: &[Mat3I],
) -> Result<Vec<(Rat, usize)>, SubductionError> {
    let mut parameters: Vec<Rat> = vec![Rat::ZERO];
    for rotation in rotations {
        let image = Mat3R::from_ints(*rotation)
            .inverse()?
            .transpose()
            .checked_mul_vector(direction)?;
        let w = image.checked_sub(direction)?;
        let Some(step) = minimal_parameter_step(lattice, &w)? else {
            continue;
        };
        let denominator = step.denominator();
        for j in 0..denominator {
            let factor = Rat::new(j, 1)?;
            let value = reduce_modulo_one(step.checked_mul(factor)?);
            if !parameters.contains(&value) {
                parameters.push(value);
            }
        }
    }
    parameters = sort_parameters(parameters)?;
    let mut out = Vec::with_capacity(parameters.len());
    for parameter in parameters {
        let mut order = 0usize;
        let mut image = [Rat::ZERO; 3];
        for (axis, value) in image.iter_mut().enumerate() {
            *value = parameter.checked_mul(direction.get(axis))?;
        }
        let k = Vec3R::new(image);
        for rotation in rotations {
            if lattice.preserves(*rotation, &k)? {
                order += 1;
            }
        }
        out.push((parameter, order));
    }
    Ok(out)
}

/// The parameter domain of one frozen source: the generic order plus every
/// exceptional parameter in `[0, 1)`.
///
/// `generic_order` is computed from the parent's own operations, so comparing it
/// with `table.operations.len()` cross-checks the frozen table against the
/// group: the frozen table is the little group of the direction, one operation
/// per distinct rotation.
pub fn parent_domain(table: &LittleCharacterTable) -> Result<ParentDomain, SubductionError> {
    let direction = line_direction(table).ok_or(SubductionError::InvalidFrozenDirection {
        sg: table.space_group,
        label: table.label,
    })?;
    let lattice = reciprocal_lattice(table.space_group)?;
    require_reciprocal_direction(&lattice, &direction, table.space_group, table.label)?;
    let rotations = rotation_set(table.space_group)?;
    let mut generic_order = 0usize;
    for rotation in &rotations {
        let image = Mat3R::from_ints(*rotation)
            .inverse()?
            .transpose()
            .checked_mul_vector(&direction)?;
        if image == direction {
            generic_order += 1;
        }
    }
    let exceptional = exceptional_parameters(&lattice, &direction, &rotations)?
        .into_iter()
        .map(|(parameter, order)| ExceptionalParameter {
            parameter,
            order,
            added: order.saturating_sub(generic_order),
        })
        .collect();
    Ok(ParentDomain {
        parent_sg: table.space_group,
        label: table.label,
        direction,
        generic_order,
        parent_rotations: rotations.len(),
        exceptional,
    })
}

/// The **candidate** parameters in `[0, 1)` of one isotropy record's folded
/// wave vector, with the child little co-group order at each.
///
/// **Reference direction only.**  This partitions the line by the folded frozen
/// direction `T^T v` alone and therefore misses every relation between *other*
/// arms (an arm gaining a little co-group, two arms merging, one arm's image
/// landing on another).  It is kept because the census's historical probes and
/// the R6.5/R6.6 numbers were built on it, and as the "reference" side of the
/// card-3 regression; new code that needs the partition of the whole star must
/// use [`full_star_partition`].  Measured: 2,273 of the 5,756 corpus pairs have a
/// strictly larger full-star partition.
///
/// The folded wave vector is `q(t) = t . T^T v`, so the same exact computation
/// applies in the child's reciprocal lattice with the child's own rotations.
/// `t = 0` is a solution of *every* operation's condition, so it is always in the
/// returned set (for a child whose point group is trivial it is not an
/// enhancement); use [`little_co_group_order`] to compare the order at any
/// parameter with the generic one.
///
/// The record's frozen direction must fold into a lattice vector of the child's
/// reciprocal lattice, otherwise `t` and `t + 1` are different folded points and
/// the domain is rejected with
/// [`SubductionError::ParameterDomainOutOfScope`].
pub fn child_exceptional_parameters(
    embedding: &SubgroupEmbedding,
    table: &LittleCharacterTable,
) -> Result<Vec<(Rat, usize)>, SubductionError> {
    let direction = line_direction(table).ok_or(SubductionError::InvalidFrozenDirection {
        sg: table.space_group,
        label: table.label,
    })?;
    let folded = fold_wave_vector(embedding.transform(), &direction)?;
    child_candidates(embedding.subgroup_sg(), &folded)
}

/// The candidate parameters of one **folded** direction in the child frame.
///
/// Split out of [`child_exceptional_parameters`] so the degenerate case is
/// testable without fabricating an embedding: `folded = 0` means the line folds
/// onto the child Gamma point, which every child rotation fixes at every
/// parameter, so the little co-group never changes and the candidate set is
/// empty (the caller sees the full child point group throughout).
pub fn child_candidates(
    child_sg: u8,
    folded: &Vec3R,
) -> Result<Vec<(Rat, usize)>, SubductionError> {
    if folded.is_zero() {
        return Ok(Vec::new());
    }
    let child_cell = Lattice::new(exact_primitive_basis(child_sg)?)?;
    let child_reciprocal = child_cell.reciprocal()?;
    require_reciprocal_direction(&child_reciprocal, folded, child_sg, "folded direction")?;
    let rotations = rotation_set(child_sg)?;
    exceptional_parameters(&child_reciprocal, folded, &rotations)
}

/// The order of the little co-group of `k(t) = t . direction` at one exact
/// parameter: how many of `rotations` fix `t . direction` modulo `lattice`.
///
/// This is defined for **every** parameter, including ones the census does not
/// list as candidates, so a caller never has to read an unknown order as zero.
pub fn little_co_group_order(
    lattice: &Lattice,
    direction: &Vec3R,
    rotations: &[Mat3I],
    parameter: Rat,
) -> Result<usize, SubductionError> {
    let k = scale(direction, &parameter)?;
    let mut order = 0usize;
    for rotation in rotations {
        if lattice.preserves(*rotation, &k)? {
            order += 1;
        }
    }
    Ok(order)
}

// ── The full-star partition ──────────────────────────────────────────────────

/// The unreduced arms of a parametric-k line: `R^-T v` for every distinct parent
/// rotation, deduplicated by **exact vector equality**.
///
/// This is the production arm list -- `decompose::line_arms` delegates here -- so
/// the partition below and the engine cannot disagree about which arms a line
/// has.  The exact (not modulo `L*`) reading is the frozen convention: the two
/// readings differ on 2,574 arm pairs of the corpus and only the exact one
/// reproduces the pinned full-star dimensions 73/73 (see
/// `decompose::line_arms` for the measurement).
///
/// **Internal**: the list is a function of the parent group, its lattice and the
/// direction; the public entry point is [`full_star_partition`].
pub(crate) fn arm_images(
    parent_sg: u8,
    parent_lattice: &Lattice,
    direction: &Vec3R,
) -> Result<Vec<(Vec3R, Mat3I)>, SubductionError> {
    let parent_ops = parent_lattice.deduplicate(&strict_sg_hall_ops(parent_sg)?.operations)?;
    let mut arms: Vec<(Vec3R, Mat3I)> = Vec::new();
    for operation in &parent_ops {
        let rotation = operation.rotation();
        let action = Mat3R::from_ints(rotation).inverse()?.transpose();
        let image = action.checked_mul_vector(direction)?;
        if arms.iter().any(|(arm, _)| *arm == image) {
            continue;
        }
        arms.push((image, rotation));
    }
    Ok(arms)
}

/// One arm of a parametric-k line **in the child frame**.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FoldedArm {
    /// `T^T (R^-T v)`: the direction whose `t`-multiple is this arm's wave
    /// vector.  Unreduced, exactly as the engine uses it.
    pub direction: Vec3R,
    /// The parent rotation the arm came from; the arm's stable identity.
    pub parent_rotation: Mat3I,
}

/// Which full-star relation a parameter boundary belongs to.
///
/// Every relation is one predicate `t (R^-T v_i - v_j) in L*_H`; the kind names
/// which part of the folded geometry it can change.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum StarEventKind {
    /// `i == j`, `R != 1`: the child rotation `R` joins the little co-group of
    /// arm `i`'s folded point, so that point's little co-group grows.
    LittleCoGroupGrowth,
    /// `i != j`, `R = 1`: two distinct arms fold onto the same child point.
    ArmMerge,
    /// `i != j`, `R != 1`: the image of arm `i` under `R` is arm `j`, so the two
    /// folded points lie in one child star.
    OrbitIdentification,
}

impl StarEventKind {
    /// Every kind, in the order the counts arrays use.
    pub const ALL: [Self; 3] = [
        Self::LittleCoGroupGrowth,
        Self::ArmMerge,
        Self::OrbitIdentification,
    ];

    /// Position in a counts array.
    pub const fn index(self) -> usize {
        match self {
            Self::LittleCoGroupGrowth => 0,
            Self::ArmMerge => 1,
            Self::OrbitIdentification => 2,
        }
    }

    /// Short human-readable name, for the census report.
    pub const fn label(self) -> &'static str {
        match self {
            Self::LittleCoGroupGrowth => "little-co-group growth",
            Self::ArmMerge => "arm merge",
            Self::OrbitIdentification => "orbit identification",
        }
    }
}

/// One exact relation of the full-star partition: the predicate
/// `t (R^-T v_arm - v_image) in L*_H`, with the arm and child rotation that
/// trigger it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StarEvent {
    /// Index into [`FullStarPartition::arms`].
    pub arm: usize,
    /// Index into [`FullStarPartition::arms`] whose point the image lands on.
    pub image: usize,
    /// The child rotation `R` of the relation.
    pub rotation: Mat3I,
    /// Which geometry the relation changes.
    pub kind: StarEventKind,
}

/// One parameter at which at least one full-star relation becomes true.
///
/// `counts` are **exact** (how many `(arm, image, rotation)` triples hold exactly
/// at this parameter); `witnesses` are bounded -- one per `(kind, arm)` pair --
/// so a boundary such as `t = 0`, where every relation holds at once, cannot blow
/// the partition up.  The geometry itself is recomputed from [`FoldArm`]s by the
/// consumer (R6.7 card 6 checks it against the production grouping); the witness
/// list is for the audit trail, not for the decision.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StarBoundary {
    /// The exact parameter in `[0, 1)`.
    pub parameter: Rat,
    /// Exact counts, indexed by [`StarEventKind::index`].
    pub counts: [usize; 3],
    /// Bounded exact witnesses.
    pub witnesses: Vec<StarEvent>,
}

/// The **full-star** parameter partition of one isotropy record: every parameter
/// at which some relation between the line's folded arms changes, plus the
/// relations that hold at every parameter.
#[derive(Debug, Clone)]
pub struct FullStarPartition {
    /// Parent space group of the frozen source.
    pub source_sg: u8,
    /// Child space group of the record's embedding.
    pub child_sg: u8,
    /// Frozen source label, e.g. `DT1`.
    pub label: &'static str,
    /// The folded arms, in the production order.
    pub arms: Vec<FoldedArm>,
    /// Index of the arm that *is* the frozen direction: the one the legacy
    /// single-direction census partitioned by.
    pub reference_arm: usize,
    /// The child's reciprocal lattice, in the frame of `arms[].direction`.
    pub child_reciprocal: Lattice,
    /// The child's distinct rotations, the `R` of the enumeration.
    pub child_rotations: Vec<Mat3I>,
    /// Boundaries in `[0, 1)`, ascending.  Empty when no relation is
    /// parameter-dependent (every predicate holds identically).
    pub boundaries: Vec<StarBoundary>,
    /// Relations whose difference vector is **zero**: they hold at every
    /// parameter of the domain and are deliberately *not* reported as boundaries.
    /// Exact counts, indexed by [`StarEventKind::index`].
    pub permanent_counts: [usize; 3],
    /// Bounded witnesses of the permanent relations (one per `(kind, arm)`).
    pub permanent_witnesses: Vec<StarEvent>,
}

impl FullStarPartition {
    /// Whether `t` is one of the partition's boundaries (reduced modulo one
    /// first: the whole geometry is periodic in `t` with period one).
    pub fn is_boundary(&self, parameter: &Rat) -> bool {
        self.boundary(parameter).is_some()
    }

    /// The boundary at `t`, if any.
    pub fn boundary(&self, parameter: &Rat) -> Option<&StarBoundary> {
        let reduced = reduce_modulo_one(*parameter);
        self.boundaries
            .iter()
            .find(|boundary| boundary.parameter == reduced)
    }

    /// The exact boundary parameters in `[0, 1)`, ascending.
    pub fn boundary_parameters(&self) -> Vec<Rat> {
        self.boundaries
            .iter()
            .map(|boundary| boundary.parameter)
            .collect()
    }

    /// The parameters the census probes for this record: the full-star
    /// boundaries together with the source's own exceptional parameters, sorted.
    ///
    /// The parent side is not implied by the child side: a parameter where two
    /// parent arms coincide modulo the parent reciprocal lattice makes the
    /// production answer a *formal* induction
    /// ([`super::decompose::ParameterKind::Formal`]) even though the folded
    /// geometry is untouched, so both sets are kept.
    pub fn probe_parameters(&self, parent: &ParentDomain) -> Result<Vec<Rat>, SubductionError> {
        let mut values: Vec<Rat> = self.boundary_parameters();
        for entry in &parent.exceptional {
            if !values.contains(&entry.parameter) {
                values.push(entry.parameter);
            }
        }
        sort_parameters(values)
    }

    /// The open intervals of the partition, as `(start, end)` in ascending order;
    /// the last one wraps around `t = 1` (`end = first + 1`).  A partition with no
    /// boundary is the single interval `(0, 1)`.
    ///
    /// The endpoints are boundaries (or `0`/`1`); the interior points are the
    /// parameters at which the folded geometry is guaranteed constant.
    pub fn intervals(&self) -> Result<Vec<(Rat, Rat)>, SubductionError> {
        let parameters = self.boundary_parameters();
        let Some(&first) = parameters.first() else {
            return Ok(vec![(Rat::ZERO, Rat::ONE)]);
        };
        let mut out = Vec::with_capacity(parameters.len());
        for (index, start) in parameters.iter().enumerate() {
            let end = match parameters.get(index + 1) {
                Some(next) => *next,
                None => first.checked_add(Rat::ONE)?,
            };
            out.push((*start, end));
        }
        Ok(out)
    }

    /// The arms grouped by folded point at one parameter: indices of arms whose
    /// `t v_i` agree modulo the child reciprocal lattice, in arm order.
    ///
    /// This is the point-level grouping the production `fold_arms` starts from;
    /// its orbit partition additionally identifies points under the child
    /// rotations (see `decompose::line_star_geometry`).  The grouping is periodic
    /// in `t` with period one because every arm is a child reciprocal vector
    /// (checked when the partition was built).
    pub fn folded_points(&self, parameter: &Rat) -> Result<Vec<Vec<usize>>, SubductionError> {
        let mut points: Vec<(Vec3R, Vec<usize>)> = Vec::new();
        'arms: for (index, arm) in self.arms.iter().enumerate() {
            let q = scale(&arm.direction, parameter)?;
            for (representative, indices) in points.iter_mut() {
                if self.child_reciprocal.same_mod(representative, &q)? {
                    indices.push(index);
                    continue 'arms;
                }
            }
            points.push((q, vec![index]));
        }
        Ok(points.into_iter().map(|(_, indices)| indices).collect())
    }
}

/// Add one event to a `(counts, witnesses)` pair.
///
/// The counts are exact; the witness list keeps one relation per `(kind, arm)`
/// so a boundary where every relation holds at once stays bounded while every
/// arm taking part is still represented.
fn record_star_event(
    counts: &mut [usize; 3],
    witnesses: &mut Vec<StarEvent>,
    event: StarEvent,
) {
    counts[event.kind.index()] += 1;
    if witnesses
        .iter()
        .any(|existing| existing.kind == event.kind && existing.arm == event.arm)
    {
        return;
    }
    witnesses.push(event);
}

/// Sort `(parameter, payload)` pairs by exact rational value.
///
/// `Rat` deliberately does not implement `Ord`; the pairs come from one record's
/// enumeration, so their denominators share a small common multiple and an
/// overflow is reported instead of falling back to `f64`.  The sort is stable, so
/// equal parameters keep the enumeration order.
fn sort_by_parameter<T>(values: Vec<(Rat, T)>) -> Result<Vec<(Rat, T)>, SubductionError> {
    let mut common: i128 = 1;
    for (parameter, _) in &values {
        common = lcm(common, parameter.denominator())?;
    }
    let mut keyed: Vec<(i128, Rat, T)> = Vec::with_capacity(values.len());
    for (parameter, payload) in values {
        let key = parameter
            .numerator()
            .checked_mul(common / parameter.denominator())
            .ok_or(SubductionError::RationalOverflow {
                operation: "full-star partition ordering",
            })?;
        keyed.push((key, parameter, payload));
    }
    keyed.sort_by_key(|(key, _, _)| *key);
    Ok(keyed
        .into_iter()
        .map(|(_, parameter, payload)| (parameter, payload))
        .collect())
}

/// The complete full-star parameter partition of one isotropy record's line.
///
/// The reference-direction census ([`child_exceptional_parameters`]) partitions
/// by the folded direction of the frozen source alone.  That is **not** enough:
/// the reported decomposition depends on the whole star, so this entry point
/// enumerates every relation that can change the folded geometry, over all
/// ordered arm pairs `(i, j)` and all child rotations `R`:
///
/// ```text
/// t (R^-T v_i - v_j) in L*_H,      v_i = T^T (R_i^-T v),
/// ```
///
/// with `i = j` covering a growth of one folded point's little co-group, `i != j`
/// with `R = 1` a merge of two arms, and `i != j` with `R != 1` an orbit
/// identification.  Every difference vector is solved with the same exact step
/// solver as the reference census ([`minimal_parameter_step`]), and a **zero**
/// difference is recorded as a permanent relation instead of a boundary: it holds
/// at every parameter, so it cuts nothing (this is the mistake the earlier
/// reference-only reading made in the opposite direction -- the reference
/// direction is exactly fixed by the whole frozen little group, so its own
/// relations are all zero and the reference partition sees nothing).
///
/// What the partition is and is not:
///
/// * It is **exact**: every parameter in `[0, 1)` is either a boundary or inside
///   exactly one open interval on which the whole folded geometry -- which arms
///   fold onto one point, which points lie in one child star, and every point's
///   little co-group -- is constant.  Each of those quantities is a truth value
///   of one of the enumerated predicates, and a predicate `t w in L*_H` with
///   `w != 0` is true exactly on the residue classes of one rational step (with
///   `w = 0` it is true everywhere), so no interval hides a change.
/// * It is **not** a statement that the engine's multiplicities are constant on
///   an interval.  That needs the per-arm factor-system argument (the M2 theorem:
///   on an interval no rotation enters a little co-group, so every arm's rotations
///   fix its direction *exactly* and its factor system is a coboundary at every
///   parameter of the interval), plus the engine-side control that the stored
///   child data and the constructed catalogue agree there.  R6.7 cards 5-6 are
///   that control; this function only supplies the partition they run on.
/// * It is **not** a partition of the reported *presentation*.  The canonical
///   block order sorts exact folded coordinates, so block indices and the
///   `stored`/`constructed` provenance of a block may change inside one interval
///   (a stored child k-point is hit at isolated parameters, and the same
///   representation can be read from either source).  Comparisons across
///   parameters must therefore match blocks by geometry and characters, never by
///   position or provenance.
///
/// The periodicity premise is checked for **every** folded arm, not only for the
/// reference one: folding must send each arm into the child's reciprocal lattice,
/// otherwise `t` and `t + 1` are different folded points and the residue
/// representation of the parameter line is invalid.  A violation is reported as
/// [`SubductionError::ParameterDomainOutOfScope`] (wrapped in
/// [`FullStarError::Subduction`], like every other failure of the line path).
pub fn full_star_partition(
    subgroup: &IsotropySubgroup,
    embedding: &SubgroupEmbedding,
    table: &'static LittleCharacterTable,
) -> Result<FullStarPartition, FullStarError> {
    super::decompose::validate_line_context(subgroup, embedding, table)?;
    let direction = line_direction(table).ok_or(SubductionError::InvalidFrozenDirection {
        sg: table.space_group,
        label: table.label,
    })?;
    let child_sg = embedding.subgroup_sg();
    let arms: Vec<FoldedArm> = arm_images(subgroup.parent_sg, embedding.parent_lattice(), &direction)?
        .into_iter()
        .map(|(arm, parent_rotation)| {
            Ok(FoldedArm {
                direction: fold_wave_vector(embedding.transform(), &arm)?,
                parent_rotation,
            })
        })
        .collect::<Result<_, SubductionError>>()?;
    let child_cell = Lattice::new(exact_primitive_basis(child_sg)?)?;
    let child_reciprocal = child_cell.reciprocal()?;
    for arm in &arms {
        require_reciprocal_direction(&child_reciprocal, &arm.direction, child_sg, table.label)?;
    }
    let reference_direction = fold_wave_vector(embedding.transform(), &direction)?;
    let reference_arm = arms
        .iter()
        .position(|arm| arm.direction == reference_direction)
        .ok_or(SubductionError::InvalidFrozenDirection {
            sg: table.space_group,
            label: table.label,
        })?;
    let child_rotations = rotation_set(child_sg)?;
    let identity = IDENTITY_ROTATION;

    let mut events: Vec<(Rat, StarEvent)> = Vec::new();
    let mut permanent_counts = [0usize; 3];
    let mut permanent_witnesses: Vec<StarEvent> = Vec::new();
    for (arm_index, arm) in arms.iter().enumerate() {
        for (image_index, image_arm) in arms.iter().enumerate() {
            for rotation in &child_rotations {
                if arm_index == image_index && *rotation == identity {
                    // The reflexive relation: an arm is itself at every
                    // parameter.  It is true by construction, not an event.
                    continue;
                }
                let image = Mat3R::from_ints(*rotation)
                    .inverse()?
                    .transpose()
                    .checked_mul_vector(&arm.direction)?;
                let difference = image.checked_sub(&image_arm.direction)?;
                let kind = if arm_index == image_index {
                    StarEventKind::LittleCoGroupGrowth
                } else if *rotation == identity {
                    StarEventKind::ArmMerge
                } else {
                    StarEventKind::OrbitIdentification
                };
                let event = StarEvent {
                    arm: arm_index,
                    image: image_index,
                    rotation: *rotation,
                    kind,
                };
                let Some(step) = minimal_parameter_step(&child_reciprocal, &difference)? else {
                    record_star_event(&mut permanent_counts, &mut permanent_witnesses, event);
                    continue;
                };
                let denominator = step.denominator();
                for multiple in 0..denominator {
                    let factor = Rat::new(multiple, 1)?;
                    let parameter = reduce_modulo_one(step.checked_mul(factor)?);
                    events.push((parameter, event));
                }
            }
        }
    }

    let mut boundaries: Vec<StarBoundary> = Vec::new();
    for (parameter, event) in sort_by_parameter(events)? {
        if boundaries
            .last()
            .is_none_or(|last| last.parameter != parameter)
        {
            boundaries.push(StarBoundary {
                parameter,
                counts: [0; 3],
                witnesses: Vec::new(),
            });
        }
        let last = boundaries.last_mut().expect("just pushed");
        record_star_event(&mut last.counts, &mut last.witnesses, event);
    }

    Ok(FullStarPartition {
        source_sg: table.space_group,
        child_sg,
        label: table.label,
        arms,
        reference_arm,
        child_reciprocal,
        child_rotations,
        boundaries,
        permanent_counts,
        permanent_witnesses,
    })
}

/// [`minimal_parameter_step`] computed through the lattice's own coordinate map.
///
/// `t . w in L*` is equivalent to `t . (C w) in Z^3` with `C` the lattice
/// coordinate matrix, so the positive generator is the least common multiple of
/// the rationals `q_i / p_i` over the nonzero components of `C w`.  This route
/// uses the lattice basis instead of the membership predicate and the centring
/// scan, so agreement between the two is a real cross-check of the scan (the
/// corpus gate compares them on every `(source, rotation)` pair).
pub fn minimal_parameter_step_via_coordinates(
    lattice: &Lattice,
    w: &Vec3R,
) -> Result<Option<Rat>, SubductionError> {
    if w.is_zero() {
        return Ok(None);
    }
    let coordinates = lattice.coordinates(w)?;
    let mut accumulated: Option<Rat> = None;
    for axis in 0..3 {
        let value = coordinates.get(axis);
        if value.is_zero() {
            continue;
        }
        let component = Rat::new(absolute(value.denominator())?, absolute(value.numerator())?)?;
        accumulated = Some(match accumulated {
            None => component,
            Some(current) => Rat::new(
                lcm(current.numerator(), component.numerator())?,
                gcd(current.denominator(), component.denominator())?,
            )?,
        });
    }
    Ok(accumulated)
}

